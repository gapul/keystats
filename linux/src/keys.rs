pub fn label_layout(k: u16, jis: bool) -> String {
    if jis {
        match k {
            13 => "^".into(),
            26 => "@".into(),
            27 => "[".into(),
            43 => "]".into(),
            40 => ":".into(),
            _ => label(k),
        }
    } else {
        label(k)
    }
}
pub fn modifier(k: u16) -> bool {
    matches!(k, 29 | 42 | 54 | 56 | 97 | 100 | 125 | 126)
}
pub fn typing(k: u16) -> bool {
    matches!(k,2..=13|16..=27|30..=41|43..=53|86|89|124)
}
pub fn correction(k: u16, ctrl: bool) -> bool {
    matches!(k, 14 | 111) || ctrl && matches!(k, 35 | 44)
}
pub fn combo(k: u16, down: &std::collections::HashSet<u16>) -> Option<String> {
    if modifier(k) {
        return None;
    }
    let ctrl = down.contains(&29) || down.contains(&97);
    let alt = down.contains(&56) || down.contains(&100);
    let super_ = down.contains(&125) || down.contains(&126);
    if !(ctrl || alt || super_) {
        return None;
    }
    let mut parts = Vec::new();
    if ctrl {
        parts.push("Ctrl".to_owned())
    }
    if alt {
        parts.push("Alt".to_owned())
    }
    if down.contains(&42) || down.contains(&54) {
        parts.push("Shift".to_owned())
    }
    if super_ {
        parts.push("Super".to_owned())
    }
    parts.push(label(k));
    Some(parts.join("+"))
}
